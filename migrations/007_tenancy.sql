-- Migration 007: multi-tenant foundation (SaaS milestone M1)
-- =============================================================================
-- People sign in as accounts (Google or an emailed link) and belong to
-- organizations, the tenants. Nothing here touches the current build's
-- tables: org_id is added to those in a later migration, when events exist.
--
-- Tenant isolation, database wall: tenant tables have Row Level Security
-- policies for the event_pass_tenant role. The API runs every tenant query inside a
-- transaction that does SET LOCAL ROLE event_pass_tenant and sets app.org_id and
-- app.account_id, so a query that forgets its WHERE org_id still only sees the
-- current organization. The connecting user (the table owner) bypasses RLS for
-- pre-tenant lookups such as sessions and invite tokens.
--
-- Safe to re-run.

-- +goose StatementBegin
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'event_pass_tenant') THEN
        CREATE ROLE event_pass_tenant NOLOGIN NOBYPASSRLS;
    END IF;
END $$;
-- +goose StatementEnd

-- The API's database user switches to event_pass_tenant for tenant transactions.
GRANT event_pass_tenant TO CURRENT_USER;

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION app_org_id() RETURNS uuid
LANGUAGE sql STABLE AS $$
    SELECT nullif(current_setting('app.org_id', true), '')::uuid
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION app_account_id() RETURNS uuid
LANGUAGE sql STABLE AS $$
    SELECT nullif(current_setting('app.account_id', true), '')::uuid
$$;
-- +goose StatementEnd

GRANT EXECUTE ON FUNCTION app_org_id(), app_account_id() TO event_pass_tenant;

-- -----------------------------------------------------------------------------
-- 1. Accounts and sign-in (not tenant-owned: one per person)
-- -----------------------------------------------------------------------------
-- IDs are UUIDv7, generated by the API, so they sort by creation time.
CREATE TABLE IF NOT EXISTS accounts (
    id            UUID PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(email)),  -- stored lower-cased
    name          VARCHAR(150) NOT NULL DEFAULT '',
    avatar_url    TEXT,
    locale        VARCHAR(20),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    last_login_at TIMESTAMPTZ
);

-- How an account signs in. provider_subject is Google's "sub" claim, or the
-- email address for emailed links.
CREATE TABLE IF NOT EXISTS auth_identities (
    provider         VARCHAR(20)  NOT NULL CHECK (provider IN ('google', 'email')),
    provider_subject VARCHAR(255) NOT NULL,
    account_id       UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (provider, provider_subject)
);
CREATE INDEX IF NOT EXISTS idx_auth_identities_account ON auth_identities (account_id);

-- Server-side sessions. The cookie holds a random token; only its SHA-256 is
-- stored, so a database leak can't be replayed as a login.
CREATE TABLE IF NOT EXISTS sessions (
    id          UUID PRIMARY KEY,
    token_hash  BYTEA NOT NULL UNIQUE,
    account_id  UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    csrf_token  VARCHAR(64) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    user_agent  VARCHAR(300) NOT NULL DEFAULT '',
    ip          VARCHAR(64)  NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_sessions_account ON sessions (account_id);

-- Emailed sign-in links: single use, short-lived, hash only.
CREATE TABLE IF NOT EXISTS login_links (
    token_hash  BYTEA PRIMARY KEY,
    email       VARCHAR(254) NOT NULL CHECK (email = lower(email)),
    next_path   VARCHAR(500) NOT NULL DEFAULT '',  -- where to go after signing in
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_login_links_email ON login_links (email, created_at);

-- -----------------------------------------------------------------------------
-- 2. Organizations (the tenants), members and invites
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orgs (
    id            UUID PRIMARY KEY,
    -- URL slug: app.example.com/o/{slug}
    slug          VARCHAR(40)  NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9](?:[a-z0-9-]{1,38}[a-z0-9])$'),
    name          VARCHAR(120) NOT NULL,
    logo_blob_id  UUID,                     -- blobs arrive with uploads (M3)
    brand_primary VARCHAR(7) CHECK (brand_primary ~ '^#[0-9A-Fa-f]{6}$'),
    plan          VARCHAR(20)  NOT NULL DEFAULT 'free' CHECK (plan IN ('free', 'pro', 'organization')),
    status        VARCHAR(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    created_by    UUID REFERENCES accounts(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS org_members (
    org_id     UUID NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    role       VARCHAR(20) NOT NULL CHECK (role IN ('owner', 'admin', 'member')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (org_id, account_id)
);
CREATE INDEX IF NOT EXISTS idx_org_members_account ON org_members (account_id);

-- Org invites now; event invites (event_id set) arrive with sharing in M2.
CREATE TABLE IF NOT EXISTS invites (
    id          UUID PRIMARY KEY,
    org_id      UUID NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    event_id    UUID,
    email       VARCHAR(254) NOT NULL CHECK (email = lower(email)),
    role        VARCHAR(20)  NOT NULL CHECK (role IN ('admin', 'member')),
    token_hash  BYTEA NOT NULL UNIQUE,
    invited_by  UUID REFERENCES accounts(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at  TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    accepted_by UUID REFERENCES accounts(id) ON DELETE SET NULL,
    revoked_at  TIMESTAMPTZ
);
-- One open org invite per address: inviting again replaces the token.
CREATE UNIQUE INDEX IF NOT EXISTS uq_invites_open_org
    ON invites (org_id, email) WHERE event_id IS NULL AND accepted_at IS NULL AND revoked_at IS NULL;

-- Every org keeps at least one owner. The org row is locked so two owners
-- stepping down at once can't both succeed. Deleting the org itself cascades
-- here after the org row is gone, which is allowed.
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION keep_one_org_owner() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF OLD.role <> 'owner' OR (TG_OP = 'UPDATE' AND NEW.role = 'owner') THEN
        RETURN COALESCE(NEW, OLD);
    END IF;
    PERFORM 1 FROM orgs WHERE id = OLD.org_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN OLD;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM org_members
                   WHERE org_id = OLD.org_id AND role = 'owner' AND account_id <> OLD.account_id) THEN
        RAISE EXCEPTION 'an organization needs at least one owner'
            USING ERRCODE = 'check_violation', CONSTRAINT = 'org_needs_owner';
    END IF;
    RETURN COALESCE(NEW, OLD);
END $$;
-- +goose StatementEnd

DROP TRIGGER IF EXISTS trg_keep_one_org_owner ON org_members;
CREATE TRIGGER trg_keep_one_org_owner
    BEFORE UPDATE OR DELETE ON org_members
    FOR EACH ROW EXECUTE FUNCTION keep_one_org_owner();

-- -----------------------------------------------------------------------------
-- 3. Row Level Security
-- -----------------------------------------------------------------------------
-- Enabled on every table, as in 001, so Supabase's public API roles see
-- nothing. Policies exist only for event_pass_tenant.
ALTER TABLE accounts        ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions        ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_links     ENABLE ROW LEVEL SECURITY;
ALTER TABLE orgs            ENABLE ROW LEVEL SECURITY;
ALTER TABLE org_members     ENABLE ROW LEVEL SECURITY;
ALTER TABLE invites         ENABLE ROW LEVEL SECURITY;

-- The tenant role can reach tenant tables only, and accounts read-only.
GRANT SELECT, INSERT, UPDATE, DELETE ON orgs, org_members, invites TO event_pass_tenant;
GRANT SELECT ON accounts TO event_pass_tenant;

-- Orgs: the current one, plus (for "my organizations") any the caller belongs to.
DROP POLICY IF EXISTS orgs_select ON orgs;
CREATE POLICY orgs_select ON orgs FOR SELECT TO event_pass_tenant
    USING (id = app_org_id()
           OR id IN (SELECT m.org_id FROM org_members m WHERE m.account_id = app_account_id()));
DROP POLICY IF EXISTS orgs_insert ON orgs;
CREATE POLICY orgs_insert ON orgs FOR INSERT TO event_pass_tenant
    WITH CHECK (id = app_org_id() AND created_by = app_account_id());
DROP POLICY IF EXISTS orgs_update ON orgs;
CREATE POLICY orgs_update ON orgs FOR UPDATE TO event_pass_tenant
    USING (id = app_org_id()) WITH CHECK (id = app_org_id());
DROP POLICY IF EXISTS orgs_delete ON orgs;
CREATE POLICY orgs_delete ON orgs FOR DELETE TO event_pass_tenant
    USING (id = app_org_id());

-- Members: read the current org's, or the caller's own memberships anywhere;
-- write only in the current org.
DROP POLICY IF EXISTS org_members_select ON org_members;
CREATE POLICY org_members_select ON org_members FOR SELECT TO event_pass_tenant
    USING (org_id = app_org_id() OR account_id = app_account_id());
DROP POLICY IF EXISTS org_members_insert ON org_members;
CREATE POLICY org_members_insert ON org_members FOR INSERT TO event_pass_tenant
    WITH CHECK (org_id = app_org_id());
DROP POLICY IF EXISTS org_members_update ON org_members;
CREATE POLICY org_members_update ON org_members FOR UPDATE TO event_pass_tenant
    USING (org_id = app_org_id()) WITH CHECK (org_id = app_org_id());
DROP POLICY IF EXISTS org_members_delete ON org_members;
CREATE POLICY org_members_delete ON org_members FOR DELETE TO event_pass_tenant
    USING (org_id = app_org_id());

DROP POLICY IF EXISTS invites_all ON invites;
CREATE POLICY invites_all ON invites FOR ALL TO event_pass_tenant
    USING (org_id = app_org_id()) WITH CHECK (org_id = app_org_id());

-- Accounts: yourself, and the members of the current org.
DROP POLICY IF EXISTS accounts_select ON accounts;
CREATE POLICY accounts_select ON accounts FOR SELECT TO event_pass_tenant
    USING (id = app_account_id()
           OR id IN (SELECT m.account_id FROM org_members m WHERE m.org_id = app_org_id()));
